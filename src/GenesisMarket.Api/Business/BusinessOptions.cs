namespace GenesisMarket.Api.Business;

/// <summary>Настройки бизнес-режима. Секция <c>Business</c>.</summary>
public sealed class BusinessOptions
{
    public const string Section = "Business";

    /// <summary>
    /// Шаблон нормализованного регистрационного номера (ЕГРЮЛ/ЕГРИП ПМР).
    ///
    /// ВНИМАНИЕ: точный формат номера в реестрах ПМР не сверен с первоисточником,
    /// поэтому по умолчанию шаблон намеренно мягкий: только цифры группами через
    /// дефис, не меньше 5 цифр («0123456», «01-023-4567»). Как только формат
    /// подтвердится — сузить здесь (или в конфиге), код не меняется.
    /// Проверяется на сохранении И повторно на подаче: ужесточённое правило
    /// действует и на реквизиты, сохранённые до него.
    /// </summary>
    public string RegistrationNumberPattern { get; set; } = @"^(?=(?:\D*\d){5})\d+(?:-\d+)*$";

    /// <summary>
    /// Пауза перед повторной подачей после ПЕРВОГО отказа, часов. Каждый следующий
    /// отказ удваивает её (24 → 48 → 96 …) до <see cref="MaxResubmitCooldownHours"/>.
    /// Считается по полям заявки в БД (ReviewedAt, RejectionCount), а не счётчиком
    /// в памяти — рестарт контейнера её не обнуляет.
    /// </summary>
    public int ResubmitCooldownHours { get; set; } = 24;

    /// <summary>Потолок паузы после отказа, часов (14 суток).</summary>
    public int MaxResubmitCooldownHours { get; set; } = 336;

    /// <summary>
    /// Минимальный интервал между любыми двумя подачами, минут. Закрывает цикл
    /// «подал → отключил режим (заявка отозвана) → подал снова», который иначе
    /// гонял бы заявку по очереди модератора без ограничений.
    /// </summary>
    public int MinMinutesBetweenSubmissions { get; set; } = 10;
}
